def slug(s):
    s = re.sub(r"[^0-9A-Za-z\u4e00-\u9fff]+", "-", s).strip("-").lower()
    return s


def build_brands():
    brands = []
    for b in BR.build_brands():
        brands.append({
            "key": b["key"],
            "name": b["zh"],
            "name_en": b["en"],
            "categories": b["categories"],
            "groups": b["groups"],
            "region": b["region"],
            "official_url": b["official_url"],
            "verified": False,          # 一律待流水线实测核验
            "verified_at": None,
            "status": "待核验",
            "evidence": None,
        })
    return brands


def build_products():
    products = []
    seen = set()
    for brand, name, cat, subtype, tags, specs, desc, release in PRODUCTS:
        pid = slug(brand) + "-" + slug(name)
        if pid in seen:
            raise SystemExit("重复产品 id: %s" % pid)
        seen.add(pid)
        products.append({
            "id": pid,
            "brand": brand,
            "name": name,
            "category": cat,
            "subtype": subtype,
            "tags": tags,
            "specs": specs,
            "description": desc,
            "release": release,
            "price_cny": None,
            "links": {
                "official": None,        # 由流水线定位品牌官网产品页
                "reviews": [],
            },
            "verification": {
                "brand_status": "待核验",
                "data_status": "seed",   # 种子数据，待多源核验升级
                "confidence": None,
                "last_checked": None,
                "notes": "种子数据：参数来自公开资料，待自动化流水线多源核验",
            },
            "discovered_at": NOW,
            "status": "published",
        })
    return products


def build_meta(brands, products):
    from collections import Counter
    cat_names = BR.CATEGORIES
    by_cat = Counter(p["category"] for p in products)
    return {
        "site": "外设水库",
        "site_key": "waishui-shuiku",
        "schema_version": 1,
        "generated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "brands": {
            "total": len(brands),
            "verified": sum(1 for b in brands if b["verified"]),
            "pending": sum(1 for b in brands if not b["verified"]),
        },
        "products": {
            "total": len(products),
            "by_category": {cat_names[k]: v for k, v in sorted(by_cat.items(), key=lambda x: -x[1])},
        },
        "last_sync": NOW,
        "pipeline": {
            "status": "待首次运行",
            "last_run": None,
            "report": None,
        },
    }


def main():
    brands = build_brands()
    products = build_products()
    meta = build_meta(brands, products)
    data_dir = os.path.join(ROOT, "data")
    os.makedirs(data_dir, exist_ok=True)
    with open(os.path.join(data_dir, "brands.json"), "w", encoding="utf-8") as f:
        json.dump({"schema_version": 1, "generated_at": NOW, "brands": brands}, f, ensure_ascii=False, indent=1)
    with open(os.path.join(data_dir, "products.json"), "w", encoding="utf-8") as f:
        json.dump({"schema_version": 1, "generated_at": NOW, "products": products}, f, ensure_ascii=False, indent=1)
    with open(os.path.join(data_dir, "meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=1)
    print("brands:", len(brands), "| products:", len(products))
    print("by_category:", meta["products"]["by_category"])
    print("brand verified:", meta["brands"]["verified"], "pending:", meta["brands"]["pending"])


if __name__ == "__main__":
    main()
